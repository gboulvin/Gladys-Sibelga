// -----------------------------------------------------------------------------
// Regenerates src/sibelga/boundaries.js: the outlines of the 19 municipalities
// of the Brussels-Capital Region, simplified, from the open UrbIS data of the
// Region (UrbIS-Adm, layer "Mu", © Paradigm / Brussels-Capital Region).
//
// A development tool, run by hand when a boundary changes (it almost never
// does): `node scripts/generate-boundaries.mjs`. It is the only place that
// downloads the data; the integration itself embeds the result and locates a
// home offline.
// -----------------------------------------------------------------------------

import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import * as prettier from 'prettier';
import { MUNICIPALITIES } from '../src/sibelga/constants.js';

const SOURCE =
  'https://geoservices-urbis.irisnet.be/geoserver/UrbisAdm/wfs?service=WFS&version=2.0.0' +
  '&request=GetFeature&typeName=UrbisAdm:Mu&outputFormat=application/json&srsName=EPSG:4326';
const OUTPUT = fileURLToPath(new URL('../src/sibelga/boundaries.js', import.meta.url));
// Largest distance, in degrees, a simplified outline may move away from the
// official one: about 10 metres.
const TOLERANCE = 0.0001;

/** Distance from a point to a segment, in degrees (flat approximation). */
function distanceToSegment([x, y], [x1, y1], [x2, y2]) {
  const dx = x2 - x1;
  const dy = y2 - y1;
  const length = dx * dx + dy * dy;
  const t = length === 0 ? 0 : Math.max(0, Math.min(1, ((x - x1) * dx + (y - y1) * dy) / length));
  return Math.hypot(x - (x1 + t * dx), y - (y1 + t * dy));
}

/** Douglas-Peucker simplification of an open line. */
function simplify(points) {
  if (points.length < 3) {
    return points;
  }
  let farthest = 0;
  let index = 0;
  for (let i = 1; i < points.length - 1; i += 1) {
    const distance = distanceToSegment(points[i], points[0], points.at(-1));
    if (distance > farthest) {
      farthest = distance;
      index = i;
    }
  }
  if (farthest <= TOLERANCE) {
    return [points[0], points.at(-1)];
  }
  return [...simplify(points.slice(0, index + 1)).slice(0, -1), ...simplify(points.slice(index))];
}

/** A closed ring, simplified in two halves so its first point is kept. */
function simplifyRing(ring) {
  const middle = Math.floor(ring.length / 2);
  return [...simplify(ring.slice(0, middle + 1)).slice(0, -1), ...simplify(ring.slice(middle))];
}

const response = await fetch(SOURCE, { signal: AbortSignal.timeout(60_000) });
if (!response.ok) {
  throw new Error(`UrbIS: HTTP ${response.status}`);
}
const { features } = await response.json();

const keyOf = (name) => MUNICIPALITIES.find(({ names }) => names.includes(name))?.key;
const boundaries = {};
for (const { key } of MUNICIPALITIES) {
  const feature = features.find((candidate) => keyOf(candidate.properties.MU_NAME_FRE) === key);
  if (!feature) {
    throw new Error(`No boundary for "${key}" in the UrbIS data`);
  }
  const polygons =
    feature.geometry.type === 'Polygon'
      ? [feature.geometry.coordinates]
      : feature.geometry.coordinates;
  // One list of rings per polygon: the outline first, then its holes.
  boundaries[key] = polygons.map((rings) => rings.map(simplifyRing));
}

const source = `// GENERATED by scripts/generate-boundaries.mjs — do not edit by hand.
//
// Outlines of the 19 municipalities of the Brussels-Capital Region, simplified
// to about 10 metres. Source: UrbIS-Adm, © Paradigm / Brussels-Capital Region,
// open data (https://datastore.brussels).
//
// municipality key -> polygons -> rings (outline, then holes) -> [longitude, latitude]
export const BOUNDARIES = ${JSON.stringify(boundaries)};
`;
const options = { ...(await prettier.resolveConfig(OUTPUT)), filepath: OUTPUT };
writeFileSync(OUTPUT, await prettier.format(source, options));
const points = Object.values(boundaries).flat(3).length;
console.log(`${OUTPUT}: ${Object.keys(boundaries).length} municipalities, ${points} points`);
